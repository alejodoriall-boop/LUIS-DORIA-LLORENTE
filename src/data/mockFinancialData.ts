export function getBusinessUnitForTransaction(tx: FinancialTransaction): BusinessUnitId {
  if (tx.businessUnit) return tx.businessUnit;
  // Fallback map based on category
  switch (tx.category) {
    case 'venta_leche':
    case 'subproductos':
    case 'venta_vacas_lecheras_registro':
      return 'lecheria';
    case 'venta_genetica':
    case 'venta_embriones':
    case 'venta_animales_puro_registro':
    case 'venta_reproductores_toros':
      return 'genetica';
    case 'venta_terneros':
      return 'crias';
    case 'venta_ganado_ceba':
    case 'compra_ganado':
    case 'fletes_transporte':
      return 'ganado_comercial';
    case 'servicio_monta_maquila':
      return 'insumos_servicios';
    case 'nomina_fija':
    case 'servicios_combustible':
    case 'impuestos_tasas':
    case 'arriendos_honorarios':
    case 'otros_gastos':
    default:
      return 'corporativo_general';
  }
}

