// GENERATE A NEW FARM FROM USER INPUT
// =========================================================================
export function generateFarmPackage(input: CreateFarmInput): FarmDataPackage {
  const farmId = `finca-${input.name
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-z0-9]/g, '-')
    .replace(/-+/g, '-')
    .replace(/^-|-$/g, '')}-${Date.now().toString().slice(-4)}`;

  const areaHa = Math.max(1, Number(input.totalAreaHa) || 100);
  const areaM2 = areaHa * 10000;
  // Compute approximate square/rect bounding box size in degrees lat/lng
  // 1 degree lat ≈ 111,000 meters
  const sideMeters = Math.sqrt(areaM2);
  const dLat = (sideMeters / 111000) * 0.55;
  const dLng = (sideMeters / (111000 * Math.cos((input.centerLat * Math.PI) / 180))) * 0.55;

  const lat = input.centerLat || 8.7525;
  const lng = input.centerLng || -75.875;

  // Realistic polygonal shape with slight natural irregularities
  const perimeterPolygon: GeoCoordinate[] = [
    { lat: lat + dLat * 0.95, lng: lng - dLng * 0.9 },
    { lat: lat + dLat * 1.05, lng: lng + dLng * 0.2 },
    { lat: lat + dLat * 0.8, lng: lng + dLng * 0.95 },
    { lat: lat - dLat * 0.1, lng: lng + dLng * 1.05 },
    { lat: lat - dLat * 0.95, lng: lng + dLng * 0.8 },
    { lat: lat - dLat * 1.0, lng: lng - dLng * 0.1 },
    { lat: lat - dLat * 0.85, lng: lng - dLng * 0.95 },
    { lat: lat + dLat * 0.1, lng: lng - dLng * 1.02 },
  ];

  const calculatedAreaM2 = calculatePolygonAreaM2(perimeterPolygon);
  const calculatedHa = m2ToHectares(calculatedAreaM2);
  const totalPerimeterM = Math.round(calculatePolygonPerimeter(perimeterPolygon));

  // Generate Paddocks
  const paddocksCount = Math.max(0, input.initialPaddocksCount || 6);
  let paddocks: PaddockGeo[] = [];

  if (paddocksCount > 0) {
    paddocks = subdividePolygonIntoPaddocks(
      perimeterPolygon,
      paddocksCount,
      input.name,
      input.predominantPasture,
      input.elevationMsnm,
    );
  }

  // Generate Contour lines
  const elev = input.elevationMsnm || 150;
  const contours: ContourLine[] = [
    {
      id: `cont-${farmId}-1`,
      elevationMsnm: elev - 10,
      isMajor: true,
      points: [
        { lat: lat + dLat * 0.7, lng: lng - dLng * 0.8 },
        { lat: lat + dLat * 0.1, lng: lng - dLng * 0.2 },
        { lat: lat - dLat * 0.6, lng: lng - dLng * 0.4 },
      ],
    },
    {
      id: `cont-${farmId}-2`,
      elevationMsnm: elev + 15,
      isMajor: false,
      points: [
        { lat: lat + dLat * 0.6, lng: lng + dLng * 0.3 },
        { lat: lat, lng: lng + dLng * 0.5 },
        { lat: lat - dLat * 0.5, lng: lng + dLng * 0.6 },
      ],
    },
  ];

  // Generate Water Infrastructure
  const waterInfra: WaterInfrastructure = {
    troughs: paddocks.slice(0, 4).map((p, idx) => ({
      id: `beb-${farmId}-${idx + 1}`,
      name: `Bebedero ${p.name} (2,500L)`,
      type: idx % 2 === 0 ? 'circular' : 'rectangular',
      capacityLiters: 2500,
      hasFloatValve: true,
      location: p.polygon[0] || { lat, lng },
      flowRateLpm: 35,
      servesPaddockCodes: [p.code],
    })),
    tanks: [
      {
        id: `tanque-${farmId}-elevado`,
        name: `Tanque Nodriza ${input.name} (25,000 L)`,
        capacityLiters: 25000,
        elevationMsnm: elev + 20,
        type: 'tanque_elevado',
        location: { lat: lat + dLat * 0.5, lng: lng + dLng * 0.3 },
      },
    ],
    sources: [
      {
        id: `fuente-${farmId}-pozo`,
        name: `Pozo Profundo y Reservorio ${input.name}`,
        type: 'pozo_profundo',
        capacityM3: 400,
        pumpType: 'solar',
        location: { lat: lat + dLat * 0.6, lng: lng + dLng * 0.4 },
      },
    ],
    pipelines: [
      {
        id: `tub-${farmId}-matriz`,
        name: 'Línea Matriz de Agua PVC 2"',
        diameterInches: '2 pulgadas',
        material: 'PVC',
        pressureType: 'gravedad',
        lengthM: Math.round(sideMeters * 1.2),
        path: [
          { lat: lat + dLat * 0.5, lng: lng + dLng * 0.3 },
          { lat, lng },
          { lat: lat - dLat * 0.4, lng: lng - dLng * 0.2 },
        ],
      },
    ],
  };

  // Generate Default Cattle Lots according to production focus
  const heads = Math.round(calculatedHa * (input.productionType === 'lecheria_especializada' ? 2.8 : 1.8));
  let lots: LotRecord[] = [];

  if (input.productionType === 'ceba') {
    lots = [
      {
        id: `lote-${farmId}-1`,
        code: 'LOTE-C01',
        name: `Lote Novillos Ceba ${input.name}`,
        category: 'ceba',
        categoryLabel: 'CEBA INTENSIVA',
        heads: Math.round(heads * 0.55),
        sexLabel: 'Machos Cebú',
        ageRange: '18-24 Meses',
        gdpCurrent: 0.88,
        currentAvgWeight: 410,
        targetWeight: 460,
        estDaysToExit: 40,
        pastureType: input.predominantPasture,
        notes: 'Lote principal de engorde.',
        historyWeights: [{ date: 'Hoy', weight: 410 }],
      },
      {
        id: `lote-${farmId}-2`,
        code: 'LOTE-C02',
        name: `Lote Levante ${input.name}`,
        category: 'cria',
        categoryLabel: 'LEVANTE',
        heads: Math.round(heads * 0.45),
        sexLabel: 'Machos Jóvenes',
        ageRange: '12-18 Meses',
        gdpCurrent: 0.72,
        currentAvgWeight: 290,
        targetWeight: 380,
        estDaysToExit: 95,
        pastureType: input.predominantPasture,
        notes: 'Lote de transición y levante.',
        historyWeights: [{ date: 'Hoy', weight: 290 }],
      },
    ];
  } else if (input.productionType === 'lecheria_especializada') {
    lots = [
      {
        id: `lote-${farmId}-1`,
        code: 'LOTE-L01',
        name: `Lote Vacas Alta Producción ${input.name}`,
        category: 'leche',
        categoryLabel: 'ALTA PRODUCCIÓN',
        heads: Math.round(heads * 0.6),
        sexLabel: 'Hembras Ordeño Doble',
        ageRange: '36-60 Meses',
        gdpCurrent: 0.6,
        currentAvgWeight: 520,
        targetWeight: 540,
        estDaysToExit: 180,
        pastureType: input.predominantPasture,
        notes: 'Promedio 22 litros/vaca/día con suplemento proteico.',
        historyWeights: [{ date: 'Hoy', weight: 520 }],
      },
    ];
  } else {
    lots = [
      {
        id: `lote-${farmId}-1`,
        code: 'LOTE-DP01',
        name: `Hato Principal ${input.name}`,
        category: 'doble_proposito' as any,
        categoryLabel: 'DOBLE PROPÓSITO',
        heads: heads,
        sexLabel: 'Machos y Hembras',
        ageRange: 'Mixto',
        gdpCurrent: 0.75,
        currentAvgWeight: 380,
        targetWeight: 450,
        estDaysToExit: 60,
        pastureType: input.predominantPasture,
        notes: 'Hato general del predio.',
        historyWeights: [{ date: 'Hoy', weight: 380 }],
      },
    ];
  }

  const profile: FarmGeoProfile = {
    id: farmId,
    name: input.name.trim(),
    legalOwner: input.legalOwner.trim() || 'Propietario Registrado',
    registrationNumber: input.registrationNumber.trim() || 'ICA-SIN-REGISTRO',
    cadastralCode: input.cadastralCode.trim() || '00000000000000000000',
    department: input.department.trim(),
    municipality: input.municipality.trim(),
    vereda: input.vereda.trim(),
    centerLat: lat,
    centerLng: lng,
    zoomLevel: 15,
    elevationMsnm: elev,
    totalAreaHa: calculatedHa,
    totalPerimeterM,
    perimeterPolygon,
    productionType: input.productionType,
    headsCount: heads,
    paddocksCount: paddocks.length,
    contactPhone: input.contactPhone,
    notes: input.notes,
    colorTag:
      input.productionType === 'genetica_pura'
        ? '#dc9a00'
        : input.productionType === 'lecheria_especializada'
        ? '#0077b6'
        : '#2d6a4f',
    lastUpdated: '08 Ago 2026',
  };

  return {
    profile,
    paddocks,
    contours,
    floodZones: [],
    waterInfra,
    lots,
    headsCount: heads,
  };
}
